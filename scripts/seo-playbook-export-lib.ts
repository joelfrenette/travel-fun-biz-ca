// The text of the exported playbook files, built from lib/seo-playbook.ts. Shared by the export script and the offline check.
import { CATEGORIES, CATEGORY_LABELS, PLAYBOOK } from '../lib/seo-playbook'
import { CHECK_IDS } from '../lib/seo-playbook-audit'

const STARS = (n: number) => '*'.repeat(n)
const EFFORT = { 1: 'quick', 2: 'an afternoon', 3: 'days' } as const
const AUTO = { auto: 'automatic', assisted: 'assisted', manual: 'manual' } as const

export function buildJson(): string {
  return JSON.stringify({ version: 1, categories: CATEGORIES.map((c) => ({ id: c, label: CATEGORY_LABELS[c] })), checks: CHECK_IDS, items: PLAYBOOK }, null, 2) + '\n'
}

export function buildMarkdown(): string {
  const lines: string[] = []
  lines.push('# SEO, AEO, GEO and local playbook', '')
  lines.push('Generated from `lib/seo-playbook.ts` by `scripts/export-seo-playbook.ts`. Do not edit this file by hand: edit the data and run the script again.', '')
  lines.push(`${PLAYBOOK.length} steps for any site that auto-blogs, grouped by area and ordered by impact (5 stars = biggest effect). "Automatic" means the site checks it by itself (the check id is shown); "assisted" means the site helps and a person finishes; "manual" means a person does it.`, '')
  lines.push('| Area | Steps |', '| --- | --- |')
  for (const c of CATEGORIES) lines.push(`| ${CATEGORY_LABELS[c]} | ${PLAYBOOK.filter((p) => p.category === c).length} |`)
  lines.push('')
  for (const c of CATEGORIES) {
    lines.push(`## ${CATEGORY_LABELS[c]}`, '')
    for (const p of PLAYBOOK.filter((x) => x.category === c)) {
      lines.push(`### ${p.title}`, '')
      lines.push(`- Id: \`${p.id}\``)
      lines.push(`- Impact: ${STARS(p.impact)} (${p.impact} of 5). Effort: ${EFFORT[p.effort]}. Who: ${AUTO[p.automation]}.`)
      lines.push(`- Applies to: ${p.appliesTo}. Source: ${p.source}.`)
      lines.push(`- Check: ${p.verify.kind === 'check' ? `automated (\`${p.verify.checkId}\`)` : 'manual'}`)
      lines.push(`- Why: ${p.why}`)
      if (p.caution) lines.push(`- Caution: ${p.caution}`)
      lines.push('- How:')
      p.how.forEach((h, i) => lines.push(`  ${i + 1}. ${h}`))
      lines.push('')
    }
  }
  return lines.join('\n')
}
