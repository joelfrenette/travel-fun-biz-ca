"use client"

import { useCallback, useEffect, useState } from "react"
import Link from "next/link"
import { Card, CardContent } from "@/components/ui/card"
import { Button } from "@/components/ui/button"
import { useToast } from "@/hooks/use-toast"
import { Loader2, Sparkles } from "lucide-react"

// Destinations whose short blurb is still empty (growth loop WP16). It reuses the Destinations screen's own
// endpoints: the list is GET /api/admin/destinations and "Generate with AI" is the same POST the Destinations
// screen uses (one model call per click, saved as an AI blurb). Nothing is generated by itself.

interface Row {
  slug: string
  destination: string
  blurb: { blurb: string } | null
}

function authHeaders(): HeadersInit {
  return { "Content-Type": "application/json", Authorization: `Bearer ${localStorage.getItem("adminToken") || ""}` }
}

export function EmptyBlurbsCard() {
  const { toast } = useToast()
  const [rows, setRows] = useState<Row[] | null>(null)
  const [error, setError] = useState("")
  const [busy, setBusy] = useState("")

  const load = useCallback(() => {
    fetch("/api/admin/destinations", { headers: authHeaders() })
      .then(async (r) => ({ ok: r.ok, body: await r.json().catch(() => ({})) }))
      .then(({ ok, body }) => {
        if (!ok) throw new Error(body.error || "Could not load the destinations")
        setRows(body.destinations || [])
        setError("")
      })
      .catch((e) => setError(e instanceof Error ? e.message : "Could not load the destinations"))
  }, [])
  useEffect(() => { load() }, [load])

  async function generate(row: Row) {
    setBusy(row.slug)
    try {
      const res = await fetch(`/api/admin/destinations/${row.slug}/generate`, { method: "POST", headers: authHeaders(), body: JSON.stringify({ destination: row.destination }) })
      const body = await res.json().catch(() => ({}))
      if (!res.ok) throw new Error(body.error || "Generation failed")
      toast({ title: `Blurb written for ${row.destination}`, description: "Read it on the Destinations screen before you rely on it." })
      load()
    } catch (e) {
      toast({ title: "Error", description: e instanceof Error ? e.message : "Failed", variant: "destructive" })
    } finally {
      setBusy("")
    }
  }

  if (error) return <div className="rounded-lg border border-destructive/50 bg-destructive/10 p-3 text-sm text-destructive">{error}</div>
  if (!rows) return null
  const empty = rows.filter((r) => !r.blurb?.blurb?.trim())
  if (empty.length === 0) return null

  return (
    <Card>
      <CardContent className="space-y-3 p-4">
        <div>
          <h2 className="font-semibold">Destinations with no blurb ({empty.length})</h2>
          <p className="text-xs text-muted-foreground">
            A blurb is the short text at the top of a /destinations page. Each click writes one with the AI (one call, general wording only, no dates or prices). Edit or remove it on the{" "}
            <Link href="/admin/destinations" className="text-primary hover:underline">Destinations screen</Link>.
          </p>
        </div>
        <ul className="divide-y">
          {empty.map((r) => (
            <li key={r.slug} className="flex flex-wrap items-center justify-between gap-3 py-2">
              <span className="text-sm font-medium">{r.destination} <span className="text-xs font-normal text-muted-foreground">/destinations/{r.slug}</span></span>
              <Button size="sm" variant="outline" disabled={!!busy} onClick={() => generate(r)}>
                {busy === r.slug ? <Loader2 className="mr-1 h-4 w-4 animate-spin" /> : <Sparkles className="mr-1 h-4 w-4" />}Generate with AI
              </Button>
            </li>
          ))}
        </ul>
      </CardContent>
    </Card>
  )
}
